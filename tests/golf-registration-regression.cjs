const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const path = require('node:path').resolve(__dirname, '../holemap-gps/registration.js');
const R = require(path);
const scale = R.metreScale(32.6);
const fromPixel = ({x,y}) => [120 + (0.3*x+0.1*y+10)/scale.lng,32.6+(-0.05*x+0.4*y-15)/scale.lat];
const points = [{x:0,y:0},{x:1000,y:0},{x:1000,y:1800},{x:0,y:1800},{x:500,y:900}];
const controls = points.map((pixel,i)=>({id:'c'+i,pixel,coordinate:fromPixel(pixel),source:'rtk',accuracy_m:0.03}));
const model = R.fit(controls);
assert.equal(model.valid,true);
assert.equal(model.quality,'calibrated');
assert.ok(model.diagnostics.rms_m < 1e-7);
assert.equal(model.diagnostics.independent.rms_m,null);
assert.ok(model.diagnostics.warnings.includes('no_independent_checkpoints'));
const serialized = JSON.parse(JSON.stringify(model));
for(let i=0;i<1000;i++){
 const pixel={x:(i*193)%1001,y:(i*337)%1801};
 const geo=R.pixelToGeo(serialized,pixel),expected=fromPixel(pixel);
 assert.ok(Math.hypot((geo[0]-expected[0])*scale.lng,(geo[1]-expected[1])*scale.lat)<1e-6);
 const back=R.geoToPixel(serialized,geo);
 assert.ok(Math.hypot(back.x-pixel.x,back.y-pixel.y)<1e-6);
}
assert.equal(R.pixelToGeo(model,{x:-1,y:0}),null);
assert.ok(R.pixelToGeo(model,{x:-1,y:0},{allowExtrapolation:true}));
assert.equal(R.containsPixel(model,{x:-1,y:0}),false);
assert.equal(R.containsPixel(model,{x:0,y:900}),true);
assert.equal(R.geoToPixel(model,fromPixel({x:-1,y:0})),null);
assert.equal(R.fit(controls.slice(0,2)).valid,false);
assert.equal(R.fit([controls[0],controls[0],controls[2]]).valid,false);
assert.equal(R.fit(controls.map((p,i)=>({...p,pixel:{x:i*100,y:0.0001*(i%2)}}))).diagnostics.degenerate,true);
const narrow=[{x:0,y:0},{x:1000,y:0},{x:1000,y:1},{x:0,y:1}].map((pixel,i)=>({id:'thin'+i,pixel,coordinate:fromPixel(pixel),source:'rtk'}));
assert.equal(R.fit(narrow).diagnostics.degenerate,true);
assert.equal(R.fit(controls.map(p=>({...p,coordinate:[120,32.6]}))).diagnostics.degenerate,true);
assert.equal(R.fit(controls.map(p=>({...p,source:'estimated-default'}))).quality,'estimated');
assert.equal(R.fit(controls.map(p=>({...p,coordinate:[181,0]}))).valid,false);
assert.equal(R.fit(controls.map(p=>({...p,pixel:{x:Infinity,y:0}}))).valid,false);
assert.equal(R.fit(controls.map(p=>({...p,accuracy_m:-1}))).valid,false);
assert.equal(R.fit([controls[0],controls[1],{...controls[2],coordinate:[-116,35]}]).valid,false);
assert.equal(R.fit(controls.slice(0,3)).diagnostics.warnings.includes('three_controls_have_no_redundancy'),true);
const pixel={x:333,y:700}, coord=fromPixel(pixel);coord[0]+=10/scale.lng;
const check=R.fit(controls,{checkpoints:[{id:'independent',pixel,coordinate:coord},controls[0],{pixel:{x:1e12,y:1e12},coordinate:[0,0]}]});
assert.equal(check.diagnostics.independent.count,1);
assert.ok(Math.abs(check.diagnostics.independent.rms_m-10)<0.001);
assert.ok(check.diagnostics.rms_m<1e-7);
assert.ok(check.diagnostics.warnings.includes('checkpoint_duplicates_control_excluded'));
assert.ok(check.diagnostics.warnings.includes('invalid_checkpoint_excluded'));
assert.equal(R.pixelToGeo({...model,valid:false},pixel),null);
assert.equal(R.geoToPixel(model,[NaN,3]),null);
assert.equal(R.isWgs84(['120',32]),false);
const context={};vm.createContext(context);vm.runInContext(fs.readFileSync(path,'utf8'),context);
assert.equal(typeof context.HoleRegistration.fit,'function');
console.log(JSON.stringify({passed:true,roundtrip_points:1000,independent_error_m:check.diagnostics.independent.rms_m,training_rms_m:model.diagnostics.rms_m,scope_rejection:true,degenerate_rejection:true,serialized_model:true,umd_browser_global:true},null,2));
